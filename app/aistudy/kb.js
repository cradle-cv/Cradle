// 本地关键词匹配：接口不可用时也能推荐知识点
export function matchLabs(text, n = 2) {
  const t = (text || '').toLowerCase()
  return LABS.map(l => ({ l, s: l.kw.reduce((a, k) => a + (t.includes(k.toLowerCase()) ? k.length : 0), 0) + (t.includes(l.title) ? 6 : 0) }))
    .filter(x => x.s > 0).sort((a, b) => b.s - a.s).slice(0, n).map(x => x.l)
}
export function matchTool(text) {
  const t = (text || '').toLowerCase()
  return Object.entries(TOOLS).find(([, v]) => v.kw.some(k => t.includes(k.toLowerCase())))?.[0] || null
}

